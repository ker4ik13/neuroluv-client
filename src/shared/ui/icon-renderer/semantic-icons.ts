export function resolveInterfaceIconName(code: string): string {
	const trimmed = code.trim();
	if (/^Fi[A-Z][A-Za-z0-9]*$/.test(trimmed)) return trimmed;
	const key = trimmed
		.replace(/^(Ai(?:Outline|Fill|Twotone)?|Bs|Fa|Ri|Pi|Gi)/, '')
		.replace(/(Fill|Line|Alt|Lg)$/, '')
		.replace(/[^a-zA-Z0-9]/g, '')
		.toLowerCase();
	return aliases[key] || 'FiGrid';
}
